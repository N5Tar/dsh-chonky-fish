import assert from 'node:assert/strict'
import { lstat, mkdir, mkdtemp, readFile, realpath, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createResources } from '../../../../app/shared/resources/index.js'
import { createMigrationRepository } from '../../../../app/shared/storage/migration/repository.js'
import * as archiveCodec from '../../../../app/shared/storage/migration/archive.js'
import { createMigrationService } from '../../migration/core.js'

const root = await mkdtemp(join(await realpath(tmpdir()), 'chonkyfish-memory-migration-'))
try {
  const sourceHome = join(root, 'source')
  const source = createResources({ homeRoot: sourceHome })
  await source.ensureLayout()
  await writeFile(source.paths.state, JSON.stringify({ version: 1, state: { name: '源鱼', prompt: '人格', balance: 1, ledger: [] } }))
  const note = '约定：每周三晚饭后散步。\n这是 2026-11-18 说好的。\n参考：https://example.com/memory-notes\n'
  const changelog = '假设：把散记并进一页。\n方法：同一组回忆任务对照。\n结果：尚未形成真实对照，不采用。\n'
  const rollback = '回退副本：每周三晚饭后散步。\n'
  await mkdir(join(source.paths.memory, 'archive', 'sessions'), { recursive: true })
  await mkdir(join(source.paths.memory, 'sessions'), { recursive: true })
  await mkdir(join(source.paths.memory, 'Sessions'), { recursive: true })
  await writeFile(join(source.paths.memory, 'notes.md'), note)
  await writeFile(join(source.paths.memory, 'CHANGELOG.md'), changelog)
  await writeFile(join(source.paths.memory, 'archive', 'notes.md'), rollback)
  await writeFile(join(source.paths.memory, 'archive', 'sessions', 'note.md'), '整理过的对照记录，不含会话定位。\n')
  await writeFile(join(source.paths.memory, 'sessions', '2026-11-01.md'), '- source-session-should-not-travel | 首次 09:00 | 最近 09:10\n')
  await writeFile(join(source.paths.memory, 'Sessions', 'local.md'), '- cased-source-index | 首次 08:00 | 最近 08:00\n')
  await mkdir(source.paths.workspace, { recursive: true })
  await writeFile(join(source.paths.workspace, 'secret-chat.md'), 'source-chat-secret')
  await writeFile(source.paths.events, 'source-chat-secret')
  const repository = createMigrationRepository({ resources: source })
  const before = await repository.fingerprintTarget()
  await writeFile(join(source.paths.memory, 'sessions', '2026-11-01.md'), '- source-session-should-not-travel | 首次 09:00 | 最近 18:00\n')
  assert.equal(await repository.fingerprintTarget(), before, '本机会话索引变化不改变迁移指纹')
  const service = createMigrationService({ resources: source, storage: repository, archiveCodec, pluginVersion: 'test' })
  const exported = await service.prepareExport()
  assert.equal(exported.sections.memory, 4)
  const archive = await service.download(exported.exportId)
  const entries = archiveCodec.readZip(archive)
  assert.equal(entries.get('memory/notes.md').toString(), note)
  assert.equal(entries.get('memory/CHANGELOG.md').toString(), changelog)
  assert.equal(entries.get('memory/archive/notes.md').toString(), rollback)
  assert.equal(entries.get('memory/archive/sessions/note.md').toString(), '整理过的对照记录，不含会话定位。\n')
  assert.equal([...entries.keys()].some(name => name.toLowerCase().startsWith('memory/sessions')), false)
  assert.equal([...entries.values()].some(value => value.includes('source-session-should-not-travel') || value.includes('cased-source-index') || value.includes('source-chat-secret')), false)

  const targetHome = join(root, 'target')
  const target = createResources({ homeRoot: targetHome })
  await target.ensureLayout()
  await target.updateConfig({ memory: { enabled: false } })
  await writeFile(target.paths.state, JSON.stringify({ version: 1, state: { name: '目标鱼', prompt: '旧人格', balance: 0, ledger: [] } }))
  await writeFile(target.paths.events, 'target-chat-secret')
  await writeFile(join(target.paths.workspace, 'secret-chat.md'), 'target-chat-secret')
  await mkdir(join(target.paths.memory, 'sessions'), { recursive: true })
  await writeFile(join(target.paths.memory, 'local-only.md'), '目标机自己的整理')
  await writeFile(join(target.paths.memory, 'sessions', '2026-11-02.md'), '- target-session-stays | 首次 10:00 | 最近 10:05\n')
  const targetRepository = createMigrationRepository({ resources: target })
  const targetService = createMigrationService({ resources: target, storage: targetRepository, archiveCodec, pluginVersion: 'test' })
  const preview = await targetService.inspect(archive)
  await targetService.commit(preview.importId)
  assert.equal(await readFile(join(target.paths.memory, 'notes.md'), 'utf8'), note)
  assert.equal(await readFile(join(target.paths.memory, 'CHANGELOG.md'), 'utf8'), changelog)
  assert.equal(await readFile(join(target.paths.memory, 'archive', 'notes.md'), 'utf8'), rollback)
  assert.equal(await readFile(join(target.paths.memory, 'archive', 'sessions', 'note.md'), 'utf8'), '整理过的对照记录，不含会话定位。\n')
  await assert.rejects(readFile(join(target.paths.memory, 'local-only.md'), 'utf8'))
  assert.equal(await readFile(join(target.paths.memory, 'sessions', '2026-11-02.md'), 'utf8'), '- target-session-stays | 首次 10:00 | 最近 10:05\n')
  await assert.rejects(readFile(join(target.paths.memory, 'sessions', '2026-11-01.md'), 'utf8'))
  assert.equal(await readFile(target.paths.events, 'utf8'), 'target-chat-secret')
  assert.equal(await readFile(join(target.paths.workspace, 'secret-chat.md'), 'utf8'), 'target-chat-secret')
  assert.equal(target.getConfig().memory.enabled, false)
  const carried = [note, changelog, rollback].join('')
  assert.equal(carried.includes('source-session-should-not-travel'), false)

  const keptHome = join(root, 'legacy')
  const kept = createResources({ homeRoot: keptHome })
  await kept.ensureLayout()
  await mkdir(join(kept.paths.memory, 'sessions'), { recursive: true })
  await writeFile(join(kept.paths.memory, 'local-only.md'), '没有 memory 段时保留')
  await writeFile(join(kept.paths.memory, 'sessions', '2026-11-03.md'), '- legacy-target-session | 首次 11:00 | 最近 11:11\n')
  const legacyEntries = archiveCodec.readZip(archive)
  const manifest = JSON.parse(legacyEntries.get('manifest.json').toString('utf8'))
  delete manifest.sections.memory
  manifest.files = manifest.files.filter(item => !item.path.startsWith('memory/'))
  const keptEntries = [...legacyEntries].filter(([name]) => name !== 'manifest.json' && !name.startsWith('memory/'))
  const legacy = archiveCodec.createZip([['manifest.json', Buffer.from(JSON.stringify(manifest))], ...keptEntries])
  const legacyRepository = createMigrationRepository({ resources: kept })
  const legacyService = createMigrationService({ resources: kept, storage: legacyRepository, archiveCodec, pluginVersion: 'test' })
  const legacyPreview = await legacyService.inspect(legacy)
  await legacyService.commit(legacyPreview.importId)
  assert.equal(await readFile(join(kept.paths.memory, 'local-only.md'), 'utf8'), '没有 memory 段时保留')
  assert.equal(await readFile(join(kept.paths.memory, 'sessions', '2026-11-03.md'), 'utf8'), '- legacy-target-session | 首次 11:00 | 最近 11:11\n')

  const malicious = archiveCodec.readZip(archive)
  const maliciousManifest = JSON.parse(malicious.get('manifest.json').toString('utf8'))
  const evil = Buffer.from('- source-session-should-not-travel | 首次 01:00 | 最近 01:00\n')
  maliciousManifest.sections.memory += 1
  maliciousManifest.files.push({ path: 'memory/sessions/evil.md', bytes: evil.length, sha256: archiveCodec.sha256(evil) })
  malicious.set('manifest.json', Buffer.from(JSON.stringify(maliciousManifest)))
  malicious.set('memory/sessions/evil.md', evil)
  await assert.rejects(() => targetService.inspect(archiveCodec.createZip([...malicious])), error => error.code === 'UNSAFE_PATH')

  const emptyHome = join(root, 'empty-source')
  const empty = createResources({ homeRoot: emptyHome })
  await empty.ensureLayout()
  await writeFile(empty.paths.state, JSON.stringify({ version: 1, state: { name: '空记忆', prompt: '', balance: 0, ledger: [] } }))
  const emptyService = createMigrationService({ resources: empty, storage: createMigrationRepository({ resources: empty }), archiveCodec, pluginVersion: 'test' })
  const emptyExport = await emptyService.prepareExport()
  assert.equal(emptyExport.sections.memory, 0)
  const clearHome = join(root, 'clear-target')
  const clear = createResources({ homeRoot: clearHome })
  await clear.ensureLayout()
  await mkdir(join(clear.paths.memory, 'sessions'), { recursive: true })
  await writeFile(join(clear.paths.memory, 'notes.md'), '将被空记忆替换')
  await writeFile(join(clear.paths.memory, 'sessions', '2026-11-04.md'), '- clear-target-session | 首次 12:00 | 最近 12:01\n')
  const clearService = createMigrationService({ resources: clear, storage: createMigrationRepository({ resources: clear }), archiveCodec, pluginVersion: 'test' })
  const clearPreview = await clearService.inspect(await emptyService.download(emptyExport.exportId))
  await clearService.commit(clearPreview.importId)
  await assert.rejects(readFile(join(clear.paths.memory, 'notes.md'), 'utf8'))
  assert.equal(await readFile(join(clear.paths.memory, 'sessions', '2026-11-04.md'), 'utf8'), '- clear-target-session | 首次 12:00 | 最近 12:01\n')

  const fileIndex = join(root, 'file-index')
  const blocked = createResources({ homeRoot: fileIndex })
  await blocked.ensureLayout()
  await writeFile(join(blocked.paths.memory, 'sessions'), 'not-a-directory')
  await writeFile(join(blocked.paths.memory, 'notes.md'), '保留到失败为止')
  const blockedService = createMigrationService({ resources: blocked, storage: createMigrationRepository({ resources: blocked }), archiveCodec, pluginVersion: 'test' })
  const blockedPreview = await blockedService.inspect(archive)
  await assert.rejects(() => blockedService.commit(blockedPreview.importId), error => error.code === 'UNSAFE_PATH' || error.code === 'IMPORT_FAILED')
  assert.equal(await readFile(join(blocked.paths.memory, 'sessions'), 'utf8'), 'not-a-directory')
  assert.equal(await readFile(join(blocked.paths.memory, 'notes.md'), 'utf8'), '保留到失败为止')

  const casedHome = join(root, 'cased-index')
  const cased = createResources({ homeRoot: casedHome })
  await cased.ensureLayout()
  await mkdir(join(cased.paths.memory, 'Sessions'), { recursive: true })
  await writeFile(join(cased.paths.memory, 'notes.md'), '目标机旧整理')
  await writeFile(join(cased.paths.memory, 'Sessions', '2026-11-02.md'), '- cased-target-session | 首次 10:00 | 最近 10:05\n')
  const casedService = createMigrationService({ resources: cased, storage: createMigrationRepository({ resources: cased }), archiveCodec, pluginVersion: 'test' })
  const casedPreview = await casedService.inspect(archive)
  await casedService.commit(casedPreview.importId)
  assert.equal(await readFile(join(cased.paths.memory, 'notes.md'), 'utf8'), note)
  assert.equal(await readFile(join(cased.paths.memory, 'Sessions', '2026-11-02.md'), 'utf8'), '- cased-target-session | 首次 10:00 | 最近 10:05\n')
  await assert.rejects(readFile(join(cased.paths.memory, 'sessions', '2026-11-01.md'), 'utf8'))

  const linkHome = join(root, 'link-index')
  const linked = createResources({ homeRoot: linkHome })
  await linked.ensureLayout()
  await writeFile(join(linked.paths.memory, 'notes.md'), '链接旁的整理')
  await symlink(join(linked.paths.memory, 'notes.md'), join(linked.paths.memory, 'sessions'))
  const linkedService = createMigrationService({ resources: linked, storage: createMigrationRepository({ resources: linked }), archiveCodec, pluginVersion: 'test' })
  const linkedPreview = await linkedService.inspect(archive)
  await assert.rejects(() => linkedService.commit(linkedPreview.importId), error => error.code === 'UNSAFE_PATH' || error.code === 'IMPORT_FAILED')
  assert.equal((await lstat(join(linked.paths.memory, 'sessions'))).isSymbolicLink(), true)
  assert.equal(await readFile(join(linked.paths.memory, 'notes.md'), 'utf8'), '链接旁的整理')

  const strayHome = join(root, 'old-pack-stray')
  const stray = createResources({ homeRoot: strayHome })
  await stray.ensureLayout()
  await mkdir(join(stray.paths.memory, 'sessions'), { recursive: true })
  await writeFile(join(stray.paths.memory, 'notes.md'), '旧包不能动')
  await writeFile(join(stray.paths.memory, 'sessions', '2026-11-05.md'), '- stray-target-session | 首次 07:00 | 最近 07:01\n')
  const strayEntries = archiveCodec.readZip(legacy)
  const strayManifest = JSON.parse(strayEntries.get('manifest.json').toString('utf8'))
  const strayNote = Buffer.from('old-pack-note\n')
  strayManifest.files.push({ path: 'memory/notes.md', bytes: strayNote.length, sha256: archiveCodec.sha256(strayNote) })
  strayEntries.set('manifest.json', Buffer.from(JSON.stringify(strayManifest)))
  strayEntries.set('memory/notes.md', strayNote)
  const strayService = createMigrationService({ resources: stray, storage: createMigrationRepository({ resources: stray }), archiveCodec, pluginVersion: 'test' })
  await assert.rejects(() => strayService.inspect(archiveCodec.createZip([...strayEntries])), error => error.code === 'INVALID_ARCHIVE')
  const sessionPack = archiveCodec.readZip(legacy)
  const sessionManifest = JSON.parse(sessionPack.get('manifest.json').toString('utf8'))
  const sessionEvil = Buffer.from('- packed-index | 首次 01:00 | 最近 01:00\n')
  sessionManifest.files.push({ path: 'memory/Sessions/evil.md', bytes: sessionEvil.length, sha256: archiveCodec.sha256(sessionEvil) })
  sessionPack.set('manifest.json', Buffer.from(JSON.stringify(sessionManifest)))
  sessionPack.set('memory/Sessions/evil.md', sessionEvil)
  await assert.rejects(() => strayService.inspect(archiveCodec.createZip([...sessionPack])), error => error.code === 'UNSAFE_PATH' || error.code === 'INVALID_ARCHIVE')
  await assert.rejects(async () => archiveCodec.readZip(archiveCodec.createZip([['memory/foo/../../sessions/x.md', Buffer.from('x')]])), error => error.code === 'UNSAFE_PATH')
  assert.equal(await readFile(join(stray.paths.memory, 'notes.md'), 'utf8'), '旧包不能动')
  assert.equal(await readFile(join(stray.paths.memory, 'sessions', '2026-11-05.md'), 'utf8'), '- stray-target-session | 首次 07:00 | 最近 07:01\n')

  const recoveryHome = join(root, 'memory-recovery')
  const recovery = createResources({ homeRoot: recoveryHome })
  await recovery.ensureLayout()
  const recoveryRepository = createMigrationRepository({ resources: recovery })
  const txDir = join(recovery.paths.migration, 'transactions', 'memory-crash')
  const stage = join(txDir, 'stage', '6')
  const backup = join(txDir, 'backup', '6')
  await mkdir(stage, { recursive: true })
  await mkdir(backup, { recursive: true })
  await writeFile(join(backup, 'old-note.md'), 'before import')
  await mkdir(join(recovery.paths.memory, 'Sessions'), { recursive: true })
  await writeFile(join(recovery.paths.memory, 'new-note.md'), 'staged import')
  await writeFile(join(recovery.paths.memory, 'Sessions', '2026-11-02.md'), '- recovered-session | 首次 10:00 | 最近 10:05\n')
  await writeFile(join(txDir, 'transaction.json'), JSON.stringify({
    phase: 'publishing', id: 'memory-crash', targets: [{ target: recovery.paths.memory, stage, backup, existed: true, preserve: ['Sessions'] }],
  }))
  await recoveryRepository.recover()
  assert.equal(await readFile(join(recovery.paths.memory, 'old-note.md'), 'utf8'), 'before import')
  assert.equal(await readFile(join(recovery.paths.memory, 'Sessions', '2026-11-02.md'), 'utf8'), '- recovered-session | 首次 10:00 | 最近 10:05\n')
  await assert.rejects(readFile(join(recovery.paths.memory, 'new-note.md'), 'utf8'))
  const outside = join(recoveryHome, 'outside-marker.txt')
  await writeFile(outside, 'must remain untouched')
  const unsafeTx = join(recovery.paths.migration, 'transactions', 'unsafe-memory')
  await mkdir(unsafeTx, { recursive: true })
  await writeFile(join(unsafeTx, 'transaction.json'), JSON.stringify({
    phase: 'publishing', id: 'unsafe-memory', targets: [{ target: recovery.paths.memory, stage: join(unsafeTx, 'stage', '6'), backup: join(unsafeTx, 'backup', '6'), existed: true, preserve: ['../sessions'] }],
  }))
  await assert.rejects(() => recoveryRepository.recover(), error => error.code === 'RECOVERY_REQUIRED')
  assert.equal(await readFile(outside, 'utf8'), 'must remain untouched')
  assert.equal(await readFile(join(recovery.paths.memory, 'Sessions', '2026-11-02.md'), 'utf8'), '- recovered-session | 首次 10:00 | 最近 10:05\n')

  const planRepository = createMigrationRepository({ resources: cased })
  await assert.rejects(() => planRepository.buildPlan({ includeMemory: true, memory: new Map([['Sessions/evil.md', Buffer.from('x')]]) }, {}), error => error.code === 'UNSAFE_PATH')
  await assert.rejects(() => planRepository.buildPlan({ includeMemory: true, memory: new Map([['../sessions/evil.md', Buffer.from('x')]]) }, {}), error => error.code === 'UNSAFE_PATH')

  console.log('memory migration: organized memories move, session indexes and chats stay')
} finally {
  await rm(root, { recursive: true, force: true })
}
